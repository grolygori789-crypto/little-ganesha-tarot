'use strict';
const fs=require('fs'); const vm=require('vm'); const assert=(v,m)=>{if(!v)throw new Error(m);};
global.window=globalThis;
const documentListeners={}; const windowListeners={};
global.document={hidden:false,addEventListener:(type,fn)=>{documentListeners[type]=fn;}};
global.window.addEventListener=(type,fn)=>{windowListeners[type]=fn;};
vm.runInThisContext(fs.readFileSync('js/reading-day.js','utf8'),{filename:'js/reading-day.js'});
const DAY=globalThis.LGTReadingDay;
assert(DAY?.version==='1.0.0','Reading Day module missing.');
const d=new Date(2026,7,23,23,14,30,0);
assert(DAY.localDateISO(d)==='2026-08-23','Local date must use device calendar date.');
const midnight=DAY.nextLocalMidnight(d);
assert(midnight.getFullYear()===2026&&midnight.getMonth()===7&&midnight.getDate()===24&&midnight.getHours()===0&&midnight.getMinutes()===0,'Next local midnight calculation failed.');
assert(DAY.formatRemaining(23*3600000+14*60000,'th')==='23 ชม. · 14 นาที','Thai hour/min countdown format failed.');
assert(DAY.formatRemaining(23*3600000+14*60000,'en')==='23 hr · 14 min','English hour/min countdown format failed.');
assert(DAY.formatRemaining(42*60000,'th')==='42 นาที','Thai minute countdown format failed.');
assert(DAY.formatRemaining(42*60000,'en')==='42 min','English minute countdown format failed.');
assert(DAY.formatRemaining(48000,'th')==='48 วินาที','Thai final-minute seconds failed.');
assert(DAY.formatRemaining(48000,'en')==='48 sec','English final-minute seconds failed.');
const source=fs.readFileSync('js/reading-day.js','utf8');
assert(source.includes('if (wasIdle) previousDate = info.localDate'),'Idle-to-new-day baseline guard missing.');
assert(source.includes('document.hidden')&&source.includes("visibilitychange")&&source.includes("pageshow"),'Background-safe countdown refresh missing.');
console.log('Reading Day local-midnight + Quiet Countdown tests: PASS');
