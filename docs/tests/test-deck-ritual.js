'use strict';
const fs=require('fs');
const assert=(value,message)=>{if(!value)throw new Error(message);};
const read=(p)=>fs.readFileSync(p,'utf8');
const index=read('index.html');
const sw=read('sw.js');
const engine=read('js/reading-engine.js');
const ritual=read('js/deck-ritual.js');
const daily=read('js/reading-ui.js');
const ask=read('js/ask-ui.js');
const three=read('js/three-ui.js');
const css=read('css/reading.css');
assert(index.includes('js/deck-ritual.js?v=0.5.0'),'Deck Ritual must load in index.');
assert(index.indexOf('js/deck-ritual.js?v=0.5.0')<index.indexOf('js/reading-ui.js?v=0.5.0'),'Deck Ritual must load before reading UIs.');
assert(sw.includes("url('js/deck-ritual.js?v=0.5.0')"),'Deck Ritual must be cached by the service worker.');
assert(engine.includes('Math.min(CONTENT.cards.length'),'Reading Engine must permit a full 78-card candidate deck.');
assert(/prepareChoice\(78\)/.test(daily),'Daily Guidance must select from the full shuffled deck.');
assert(/variant:\s*'quick'/.test(daily)&&/rowCount:\s*3/.test(daily),'Daily must use the compact 3-row ritual.');
assert(/prepareChoice\(78\)/.test(ask),'Ask Ganesha must select from the full shuffled deck.');
assert(/variant:\s*'focus'/.test(ask)&&/rowCount:\s*3/.test(ask),'Ask must use the focused 3-row ritual.');
assert(/prepareChoice\(78\)/.test(three),'Three-Card must select from the full shuffled deck.');
assert(/selectionLimit:\s*3/.test(three)&&/variant:\s*'full'/.test(three)&&/rowCount:\s*3/.test(three),'Three-Card must use the full 3x26 ritual.');
assert(ritual.includes("version: '1.0.0'")&&ritual.includes("aria-pressed")&&ritual.includes("ArrowRight")&&ritual.includes("ArrowDown"),'Deck Ritual accessibility/keyboard behavior missing.');
assert(css.includes('.deck-ritual__card +')===false,'Deck cards should not use overlapping hit boxes.');
assert(css.includes('--deck-step')&&css.includes('.deck-ritual__card-shell'),'Deck Ritual must separate tap strips from overlapping visuals.');
console.log('Shared 78-card Deck Ritual wiring/accessibility tests: PASS');
